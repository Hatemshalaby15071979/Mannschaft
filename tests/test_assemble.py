def test_timeline_starts_at_zero_and_covers_every_segment(built):
    script, result, _ = built
    assert [e.id for e in result.timeline] == [s.id for s in script.segments]
    assert result.timeline[0].start_ms == 0
    assert all(e.end_ms > e.start_ms for e in result.timeline)
    assert all(a.end_ms <= b.start_ms for a, b in zip(result.timeline, result.timeline[1:], strict=False))


def test_timeline_matches_authored_gaps(built):
    script, result, _ = built
    for i, seg in enumerate(script.segments[:-1]):
        assert result.timeline[i + 1].start_ms == result.timeline[i].end_ms + seg.gaps()[-1]


def test_repeat_expands_the_span_not_the_entry_count(built):
    script, result, _ = built
    by_id = {e.id: e for e in result.timeline}
    echo = by_id["s2"]
    assert echo.takes == 2
    # two takes + one intra gap, which is max(300, pause_after_ms // 2)
    clip = echo.duration_ms - max(300, 600 // 2)
    assert clip % 2 == 0
    assert clip // 2 > 0
    drill = by_id["s4"]
    assert drill.takes == 3
    assert drill.duration_ms > echo.duration_ms


def test_check_exposes_its_thinking_time(built):
    script, result, _ = built
    check = next(e for e in result.timeline if e.id == "s3")
    assert check.answer_pause_ms == 1200
    assert check.pause_after_ms == 400
    # the tail after a check is the thinking time, not the ordinary pause
    after = next(e for e in result.timeline if e.start_ms == check.end_ms + 1200)
    assert after is not None


def test_non_check_entries_have_no_answer_pause(built):
    _, result, _ = built
    assert [e.id for e in result.timeline if e.answer_pause_ms is not None] == ["s3"]


def test_entry_carries_the_config_voice_key_not_a_profile_id(built):
    _, result, _ = built
    voices = {e.voice for e in result.timeline}
    assert voices == {"de_narrator_f", "de_young_f"}
    assert not any(v.startswith("pid-") for v in voices)


def test_build_timeline_rejects_a_missing_clip():
    script = make_script()
    with pytest.raises(AssemblyError, match="no rendered audio"):
        build_timeline(script, {"s1": 1000})


