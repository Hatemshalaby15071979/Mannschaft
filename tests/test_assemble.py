"""M5 — ffmpeg assembler: lesson.mp3, timeline.json, lesson.srt, manifest.json.

Every test here runs on synthetic tones generated by ffmpeg, so it needs no
VoiceStudio, no GPU and no M4 voices. The assertions are about timing and
loudness, which are exactly the things that silently go wrong.
"""

