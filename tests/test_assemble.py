def test_assembled_duration_matches_the_timeline(built):
    script, result, _ = built
    last = result.timeline[-1]
    assert result.duration_ms == last.end_ms  # s4 has pause_after_ms=0
    assert abs(result.drift_ms) <= MAX_DRIFT_MS, f"drift {result.drift_ms} ms"


def test_written_files_exist(built):
    _, result, out = built
    for path in (result.audio_path, result.timeline_path, result.srt_path, result.manifest_path):
        assert path.exists() and path.stat().st_size > 0, path
    assert result.audio_path.name == "lesson.mp3"
    assert result.audio_path.parent == out


def test_mp3_duration_agrees_with_timeline(built):
    _, result, _ = built
    measured = probe_duration_ms(result.audio_path)
    assert abs(measured - result.duration_ms) <= MAX_DRIFT_MS


def test_line_clips_are_written_per_segment(built):
    script, result, _ = built
    produced = sorted(p.stem for p in result.lines_dir.glob("*.mp3"))
    assert produced == sorted(s.id for s in script.segments)
    by_id = {e.id: e for e in result.timeline}
    for seg in script.segments:
        entry = by_id[seg.id]
        clip_span = entry.duration_ms - seg.intra_take_pause_ms * (seg.takes - 1)
        expected = clip_span // seg.takes
        actual = probe_duration_ms(result.lines_dir / f"{seg.id}.mp3")
        assert abs(actual - expected) <= 60, f"{seg.id}: {actual} ms vs {expected} ms"


def test_timeline_json_is_a_bare_ordered_array(built):
    _, result, _ = built
    data = json.loads(result.timeline_path.read_text(encoding="utf-8"))
    assert isinstance(data, list)
    assert [e["id"] for e in data] == [e.id for e in result.timeline]
    assert set(data[0]) >= {"id", "start_ms", "end_ms", "speaker", "voice", "type"}
    starts = [e["start_ms"] for e in data]
    assert starts == sorted(starts)


def test_srt_matches_the_timeline(built):
    _, result, _ = built
    srt = result.srt_path.read_text(encoding="utf-8")
    assert "Eins." in srt and "One." in srt
    assert "00:00:00,000 -->" in srt
    # checks are audio-only; the answer belongs to the UI
    assert "Wie viele?" not in srt


def test_loudness_is_within_one_lu_of_target(built):
    _, result, _ = built
    measured = measure_loudness(result.audio_path)
    got = float(measured["input_i"])
    assert abs(got - TARGET_I) <= 1.0, f"integrated loudness {got} LUFS, target {TARGET_I}"


def test_manifest_records_provenance(built):
    script, result, _ = built
    manifest = json.loads(result.manifest_path.read_text(encoding="utf-8"))
    assert manifest["lesson_id"] == "A1-99"
    assert manifest["script_hash"] == script_hash(script)
    assert manifest["segments"] == len(script.segments)
    assert set(manifest["durations"]) == {s.id for s in script.segments}
    assert manifest["voice_ids"]["narrator"]["voice"] == "de_narrator_f"
    assert manifest["sample_rate"] == 24000
    assert manifest["target_lufs"] == TARGET_I


def test_build_directory_is_cleaned_up(built):
    _, result, out = built
    assert not (out / "build").exists()
    assert result.lines_dir.exists()


def test_keep_build_keeps_the_intermediates(fixture_audio, tmp_path):
    script, lines = fixture_audio
    out = tmp_path / "keep"
    assemble(script, lines, out, keep_build=True)
    assert (out / "build" / "lesson.raw.wav").exists()
    assert (out / "build" / "graph.txt").exists()


