def test_trim_removes_edge_silence_but_keeps_40ms(tmp_path):
    src = make_clip(tmp_path / "padded.wav", 1.0)
    dst = tmp_path / "trimmed.wav"
    trim_clip(src, dst)
    assert probe_duration_ms(src) == 1300
    # 1.0 s tone + 40 ms guard each side; allow a sample of slack
    assert 1060 <= probe_duration_ms(dst) <= 1100


def test_silent_clip_fails_loudly(tmp_path):
    silent = make_silence(tmp_path / "silent.wav")
    trimmed = tmp_path / "silent_trimmed.wav"
    trim_clip(silent, trimmed)
    with pytest.raises(AssemblyError, match="silence|duration"):
        probe_duration_ms(trimmed)


