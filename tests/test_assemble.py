def test_missing_segment_audio_is_rejected(fixture_audio, tmp_path):
    script, lines = fixture_audio
    partial = {k: v for k, v in lines.items() if k != "s3"}
    with pytest.raises(AssemblyError, match="no rendered wav for: s3"):
        assemble(script, partial, tmp_path / "out")


def test_silent_segment_aborts_the_assembly(fixture_audio, tmp_path):
    script, lines = fixture_audio
    broken = dict(lines)
    broken["s2"] = make_silence(tmp_path / "silent_s2.wav")
    with pytest.raises(AssemblyError, match="silence|duration"):
        assemble(script, broken, tmp_path / "out")


def test_script_hash_changes_when_a_line_changes():
    a = make_script()
    b = a.model_copy(update={"segments": [a.segments[0].model_copy(update={"text": "Eins!"}), *a.segments[1:]]})
    assert script_hash(a) != script_hash(b)
    assert script_hash(a) == script_hash(make_script())


def test_timeline_entry_serialises_optional_fields():
    entry = TimelineEntry(
        id="s1", start_ms=0, end_ms=500, speaker="narrator", voice="de_narrator_f",
        type="line", text="Eins.", translation=None, takes=1, pause_after_ms=300,
    )
    data = entry.as_dict()
    assert "translation" not in data
    assert "answer_pause_ms" not in data
    assert entry.duration_ms == 500
