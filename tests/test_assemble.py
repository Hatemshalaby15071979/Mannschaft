# tone length per segment id, before the 150 ms of padding each side
# The product needs ffmpeg; make check should stay green on machines without it.
pytestmark = pytest.mark.skipif(
    shutil.which("ffmpeg") is None or shutil.which("ffprobe") is None,
    reason="ffmpeg/ffprobe not installed",
)

TONE_S = {"s1": 1.0, "s2": 0.6, "s3": 0.8, "s4": 0.5}
FREQ = {"s1": 440, "s2": 550, "s3": 660, "s4": 770}


def make_script() -> LessonScript:
    return LessonScript.model_validate(
        {
            "id": "A1-99",
            "level": "A1",
            "title": {"de": "Assembler-Probe", "en": "Assembler probe"},
            "minutes": 1,
            "scene": {
                "setting_de": "Ein Test.",
                "setting_en": "A test.",
                "register": "neutral",
                "can_do_de": "Ich kann testen.",
                "can_do_en": "I can test.",
                "situation_tags": ["test"],
                "grammar_focus": ["test"],
            },
            "cast": [
                {"role": "narrator", "voice": "de_narrator_f"},
                {"role": "kunde", "voice": "de_young_f"},
            ],
            "segments": [
                {
                    "id": "s1", "type": "line", "speaker": "narrator",
                    "text": "Eins.", "translation": "One.", "pause_after_ms": 300,
                },
                {
                    "id": "s2", "type": "echo", "speaker": "kunde",
                    "text": "Zwei.", "translation": "Two.", "repeat": 2,
                    "speed": 0.85, "pause_after_ms": 600,
                },
                {
                    "id": "s3", "type": "check", "speaker": "narrator",
                    "text": "Wie viele?", "translation": "How many?",
                    "answers": ["zwei"], "answer_pause_ms": 1200, "pause_after_ms": 400,
                },
                {
                    "id": "s4", "type": "drill", "speaker": "kunde",
                    "text": "Drei.", "translation": "Three.", "repeat": 3,
                    "speed": 0.85, "pause_after_ms": 0,
                },
            ],
            "glossary": [],
        }
    )


@pytest.fixture(scope="module")
def fixture_audio(tmp_path_factory) -> tuple[LessonScript, dict[str, Path]]:
    root = tmp_path_factory.mktemp("asm-in")
    script = make_script()
    lines = {
        seg.id: make_clip(root / f"{seg.id}.wav", TONE_S[seg.id], FREQ[seg.id])
        for seg in script.segments
    }
    return script, lines


@pytest.fixture(scope="module")
def built(fixture_audio, tmp_path_factory):
    script, lines = fixture_audio
    out = tmp_path_factory.mktemp("asm-out")
    result = assemble(script, lines, out, voices=load_voices(), level=load_levels()[script.level])
    return script, result, out


